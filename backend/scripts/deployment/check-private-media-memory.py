#!/usr/bin/env python3
"""Run synthetic private-media HTTP load in an isolated 384 MiB Linux container.

Usage: sudo python3 check-private-media-memory.py pawworldcare-backend:<reviewed-sha>
Requires an already built image. No production env, volumes, ports or network.
"""
import os
from pathlib import Path
import re
import subprocess
import sys
import uuid


def main():
    if sys.platform != 'linux' or os.geteuid() != 0:
        raise SystemExit('Run as root on a Linux Docker host')
    image = sys.argv[1] if len(sys.argv) == 2 else ''
    if not re.fullmatch(r'pawworldcare-backend:[a-f0-9]{40}', image):
        raise SystemExit('Supply an already built release image with a full SHA tag')
    memory = Path('/proc/meminfo').read_text()
    available = re.search(r'^MemAvailable:\s+(\d+) kB', memory, re.M)
    if not available or int(available.group(1)) < 900 * 1024:
        raise SystemExit('Insufficient spare RAM; use a separate acceptance host')
    subprocess.run(['docker', 'image', 'inspect', image], check=True,
                   stdout=subprocess.DEVNULL)
    suffix = uuid.uuid4().hex[:12]
    network = 'pwc-media-audit-' + suffix
    mongo = network + '-mongo'
    workload = network + '-node'
    script = Path(__file__).with_name('private-media-memory-check.mjs').resolve()
    network_created = False
    try:
        subprocess.run(['docker', 'network', 'create', '--internal', network],
                       check=True, stdout=subprocess.DEVNULL)
        network_created = True
        subprocess.run(['docker', 'run', '-d', '--name', mongo, '--network', network,
                        '--network-alias', 'pwc-audit-mongo', '--memory', '384m', '--memory-swap', '384m',
                        '--cpus', '0.5', '--tmpfs', '/data/db:rw,size=1g', '--tmpfs', '/data/configdb:rw,size=16m',
                        'mongo:8.0@sha256:b9924c330a8bbc5800fe9c69f04a84e221eca7b28fd049a0354147d9908fa142',
                        'mongod', '--replSet', 'audit', '--bind_ip_all',
                        '--wiredTigerCacheSizeGB', '0.25'], check=True,
                       stdout=subprocess.DEVNULL)
        result = subprocess.run(['docker', 'run', '--rm', '--name', workload,
                                 '--network', network, '--memory', '384m', '--memory-swap', '384m', '--cpus', '0.5',
                                 '-v', str(script) + ':/audit/memory.mjs:ro', image,
                                 'node', '/audit/memory.mjs'], timeout=180)
        if result.returncode:
            raise SystemExit(result.returncode)
    finally:
        if network_created:
            # Only unique names generated by this invocation; never production resources.
            for name in (workload, mongo):
                subprocess.run(['docker', 'rm', '-fv', name],
                               stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            subprocess.run(['docker', 'network', 'rm', network],
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


if __name__ == '__main__':
    main()
